def test_keyword_search_returns_filtered_results(client, make_paper) -> None:
    """?q=<keyword> filters papers by title / abstract / authors."""
    make_paper("ks-p1", title="DAS fibre optic seismology",
               authors=["Alice Smith"], abstract="Distributed Acoustic Sensing method")
    make_paper("ks-p2", title="Earthquake early warning",
               authors=["Bob Jones"], abstract="GNSS-based magnitude estimation")

    # Search mode (q given) queries the whole candidate pool — including
    # un-collected papers — so make_paper() rows are discoverable even though
    # the no-q "All papers" view is now scoped to the library.
    # Title match (case-insensitive)
    r = client.get("/api/papers?q=DAS")
    assert r.status_code == 200
    body = r.json()
    assert body["q"] == "DAS"
    ids = {p["id"] for p in body["papers"]}
    assert "ks-p1" in ids
    assert "ks-p2" not in ids

    # Abstract match (lowercase)
    r2 = client.get("/api/papers?q=gnss")
    assert "ks-p2" in {p["id"] for p in r2.json()["papers"]}

    # Author match
    r3 = client.get("/api/papers?q=alice")
    assert "ks-p1" in {p["id"] for p in r3.json()["papers"]}

    # No match
    r4 = client.get("/api/papers?q=xyznonexistent9999")
    assert r4.json()["count"] == 0


